# Builds UnityRTX and, with -Deploy, installs it into a Unity game:
#
#   <game>\BepInEx\plugins\UnityRTX\
#     UnityRemix.dll, UnityRTXHostPass.dll   the plugin and its D3D11 capture
#     openremix\                             OpenRemix's runtime (package-runtime.py's bundle)
#
# Examples:
#   .\scripts\build.ps1 -GamePath "C:\...\ULTRAKILL"                     # build only
#   .\scripts\build.ps1 -GamePath "C:\...\ULTRAKILL" -Deploy             # plugin + host-pass DLL
#   .\scripts\build.ps1 -GamePath "C:\...\ULTRAKILL" -Deploy -Native `
#       -OpenRemix "C:\...\OpenRemix" -OpenRemixBuild _work\build\windows-usd   # everything
param(
    [Parameter(Mandatory = $true)][string]$GamePath,
    [switch]$Deploy,
    [switch]$Native,              # rebuild native\ (UnityRTXHostPass.dll) with Meson first
    [string]$OpenRemix = "",      # an OpenRemix checkout: with -Deploy, its runtime is packaged and installed
    [string]$OpenRemixBuild = "_work\build\windows"
)
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$src = Join-Path $root "src"

function Step($text) { Write-Host "== $text" -ForegroundColor Cyan }

if (-not (Test-Path $GamePath)) { throw "Game folder not found: $GamePath" }
$data = Get-ChildItem $GamePath -Directory -Filter "*_Data" | Where-Object { Test-Path (Join-Path $_.FullName "Managed") } | Select-Object -First 1
if (-not $data) { throw "No *_Data\Managed folder in $GamePath (a Unity Mono game is required)" }
$managed = Join-Path $data.FullName "Managed"
$core = Join-Path $GamePath "BepInEx\core"
if (-not (Test-Path $core)) { throw "BepInEx\core not found in ${GamePath}: install BepInEx 5 first" }

Step "References from $($data.Name)"
$lib = Join-Path $src "lib"
New-Item -ItemType Directory -Force $lib | Out-Null
# The project's references (src\UnityRTX.csproj).
$references = @("BepInEx.dll", "0Harmony.dll") | ForEach-Object { Join-Path $core $_ }
$references += @("UnityEngine", "UnityEngine.CoreModule", "UnityEngine.UIModule", "UnityEngine.UI",
                 "UnityEngine.AnimationModule", "UnityEngine.ParticleSystemModule", "UnityEngine.TerrainModule") |
    ForEach-Object { Join-Path $managed "$_.dll" }
foreach ($reference in $references) {
    if (Test-Path $reference) { Copy-Item $reference $lib -Force }
    else { Write-Host "  missing (optional for this game?): $reference" -ForegroundColor Yellow }
}

Step "Plugin"
$hash = "unknown"
try { $hash = (git -C $root rev-parse --short HEAD).Trim() } catch {}
Set-Content (Join-Path $src "BuildInfo.cs") -Encoding UTF8 -Value @"
// Auto-generated by scripts\build.ps1 - do not edit
namespace UnityRemix
{
    public static class BuildInfo
    {
        public const string GitHash = "$hash";
    }
}
"@
dotnet build (Join-Path $src "UnityRTX.csproj") --configuration Release
if ($LASTEXITCODE) { throw "dotnet build failed" }

$nativeDll = Join-Path $root "native\_build\hostpass11\UnityRTXHostPass.dll"
if ($Native) {
    Step "Native (Meson, clang-cl)"
    $vs = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -property installationPath
    Import-Module "$vs\Common7\Tools\Microsoft.VisualStudio.DevShell.dll"
    Enter-VsDevShell -VsInstallPath $vs -SkipAutomaticLocation -DevCmdArguments "-arch=x64 -host_arch=x64" | Out-Null
    $env:CC = "clang-cl"; $env:CXX = "clang-cl"
    Push-Location (Join-Path $root "native")
    try {
        if (-not (Test-Path "_build\build.ninja")) { meson setup _build --buildtype=release; if ($LASTEXITCODE) { throw "meson setup failed" } }
        ninja -C _build; if ($LASTEXITCODE) { throw "native build failed" }
    } finally { Pop-Location }
}

if (-not $Deploy) {
    Write-Host "Built. Add -Deploy to install into $GamePath" -ForegroundColor Green
    exit 0
}

$dest = Join-Path $GamePath "BepInEx\plugins\UnityRTX"
Step "Deploy to $dest"
New-Item -ItemType Directory -Force $dest | Out-Null
# Games whose runtime has netstandard 2.1 (Unity 2021.2+) take the netstandard2.1 build;
# older ones (no netstandard.dll, or 2.0's, as DUSK's Unity 2018) take net472.
$netstandard = Join-Path $managed "netstandard.dll"
$framework = "net472"
if (Test-Path $netstandard) {
    $nsVersion = [Reflection.AssemblyName]::GetAssemblyName($netstandard).Version
    if ($nsVersion -ge [Version]"2.1.0.0") { $framework = "netstandard2.1" }
}
$bin = Join-Path $src "bin\Release\$framework"
Copy-Item (Join-Path $bin "UnityRemix.dll"), (Join-Path $bin "UnityRemix.pdb") $dest -Force
Write-Host "  UnityRemix.dll ($framework)"
if (Test-Path $nativeDll) { Copy-Item $nativeDll $dest -Force; Write-Host "  UnityRTXHostPass.dll" }
else { Write-Host "  UnityRTXHostPass.dll not built (add -Native): shader pass-through stays off" -ForegroundColor Yellow }

if ($OpenRemix) {
    Step "OpenRemix runtime from $OpenRemix\$OpenRemixBuild"
    $build = Join-Path $OpenRemix $OpenRemixBuild
    $sdl = Join-Path $OpenRemix "_work\deps\windows\prefix\bin\SDL3.dll"
    $package = Join-Path ([IO.Path]::GetTempPath()) ("unityrtx-runtime-" + [guid]::NewGuid().ToString("N"))
    python (Join-Path $OpenRemix "scripts\windows\package-runtime.py") --build $build --sdl $sdl --output $package
    if ($LASTEXITCODE) { throw "package-runtime.py failed" }
    $runtime = Join-Path $dest "openremix"
    New-Item -ItemType Directory -Force $runtime | Out-Null
    # Files already there and not in the bundle (DLSS 5's, a .pdb) are kept.
    robocopy $package $runtime /E /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "copying the runtime failed (robocopy $LASTEXITCODE)" }
    $pdb = Join-Path $build "src\native\remix.pdb"
    if (Test-Path $pdb) { Copy-Item $pdb $runtime -Force }
    Remove-Item -Recurse -Force $package
    Write-Host "  runtime installed in $runtime"
}
elseif (-not (Test-Path (Join-Path $dest "openremix\remix.dll"))) {
    Write-Host "  No OpenRemix runtime in $dest\openremix (pass -OpenRemix <checkout>)" -ForegroundColor Yellow
}

$legacy = @("remix.dll", "SDL3.dll", "usd_tf.dll", "UnityRTXHostPass.dll") | Where-Object { Test-Path (Join-Path $GamePath $_) }
if ($legacy) {
    Write-Host "Note: the game folder still has files of the old layout ($($legacy -join ', ')); UnityRTX no longer uses them once $dest\openremix has a runtime." -ForegroundColor Yellow
}
Write-Host "Done. Restart the game to load the new files." -ForegroundColor Green
